const CACHE_POINT = { anthropic: { cacheControl: { type: "ephemeral" } } };

export interface SystemBlock {
  role: "system";
  content: string;
  providerOptions?: typeof CACHE_POINT;
}

// 今日の日付はキャッシュの境目のあとに置く。日が変わっても、前のブロックのキャッシュが使える。
export function buildSystem(today: string): readonly SystemBlock[] {
  return deepFreeze([
    { role: "system", content: STABLE_PROMPT, providerOptions: CACHE_POINT },
    {
      role: "system",
      content: `今日は ${today}（${weekdayOf(today)}曜日）です。日付の計算は、この日を起点にしてください。`,
    },
  ]);
}
