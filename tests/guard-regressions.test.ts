test("固定表: 要る額の範囲の照合", () => {
  const { first } = exampleMoneyTurns();
  const args = { toolEvents: first.calculations, userTexts: [], today: "2026-11-30" };
  for (const [round, reply, flagged] of RANGE) {
    const warnings = checkReply({ ...args, reply });
    assert.equal(warnings.length > 0 ? 1 : 0, flagged, `${round}: ${reply} ${JSON.stringify(warnings)}`);
    if (flagged === 0) assert.equal(maskUnverified({ ...args, reply }).masked, 0, `${round}: ${reply}`);
  }
});
